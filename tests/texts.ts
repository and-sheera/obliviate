// Realistic texts with people and companies, and ordinary texts that must stay untouched.
// Used twice:
//   tests/texts.test.ts — strict, no model: `hide` must go, `keep` must stay, negatives must not change at all
//   tests/ner.bench.ts  — the real model: recall on `per`/`org`, precision, share of clean negatives
import type { Type } from '../src/core/types';

export type Kind =
  | 'letter' | 'chat' | 'ticket' | 'crm' | 'hr' | 'legal' | 'meeting' | 'form'
  | 'prompt' | 'names' | 'company' | 'famous' | 'english' | 'transcript';

export interface TextCase {
  kind: Kind;
  text: string;
  /** people that must be hidden, exactly as written (every occurrence) */
  per?: string[];
  /** companies that must be hidden, exactly as written (every occurrence) */
  org?: string[];
  /** must be hidden even without the model: emails, phones, ООО «X», Иванов И.И., ИП … */
  hide?: string[];
  /** must never be hidden */
  keep?: string[];
  /** may be hidden or not: latin brands, streets, product names */
  maybe?: string[];
  /** out of reach for the model (english, lowercase chat): reported, not part of the thresholds */
  info?: true;
}

export interface Negative {
  kind: string;
  text: string;
  /** reported, not part of the threshold */
  info?: true;
}

